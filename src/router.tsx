export function routeToHash(route: Route): string {
  switch (route.name) {
    case 'home':
      return '#/'
    case 'sites':
      return '#/sites'
    case 'site':
      return `#/site/${encodeURIComponent(route.id)}`
    case 'stories':
      return '#/stories'
    case 'story':
      return `#/story/${encodeURIComponent(route.id)}`
    case 'timeline':
      return '#/timeline'
    case 'map':
      return '#/map'
    case 'journey':
      return '#/journey'
    case 'quiz':
      return '#/quiz'
    case 'about':
      return '#/about'
    case 'pipeline':
      return '#/pipeline'
    case 'folklore':
      return '#/folklore'
  }
}

/** Change page. Scrolls to top, because every page starts at its head. */
export function navigate(route: Route, replace = false): void {
  const next = routeToHash(route)
  if (window.location.hash === next) return

  if (replace) {
    window.history.replaceState(null, '', next)
    // replaceState does not fire hashchange, so notify by hand
    window.dispatchEvent(new HashChangeEvent('hashchange'))
  } else {
    window.location.hash = next
  }
}


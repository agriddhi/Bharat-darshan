"""Download the latin-subset woff2 files from a Google Fonts stylesheet
and rewrite the stylesheet to point at local copies.

Only the `latin` block of each @font-face is kept. The other subsets
(cyrillic, greek, vietnamese...) would each add a file the site never
uses, and every one of them is a request that can fail on a bad
connection. Keeping latin alone means the whole type system is two
requests' worth of bytes and works with no network at all.

Run:  python tools/fetch_fonts.py
"""

import os
import re
import subprocess
import sys

UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

HERE = os.path.dirname(os.path.abspath(__file__))
V2 = os.path.dirname(HERE)
OUT_CSS_DIR = os.path.join(V2, "public", "fonts")
OUT_FONT_DIR = os.path.join(OUT_CSS_DIR)

SRC_CSS = os.path.join(os.environ.get("TEMP", "/tmp"), "fonts", "gf.css")
FALLBACK = r"C:\Users\Gaupad\AppData\Local\Temp\opencode\fonts\gf.css"

if not os.path.exists(SRC_CSS):
    SRC_CSS = FALLBACK

# Each block is preceded by a /* subset */ comment Google emits.
BLOCK_RE = re.compile(
    r"(/\*\s*([a-z0-9-]+)\s*\*/\s*)?(@font-face\s*\{.*?\})",
    re.S | re.I,
)
URL_RE = re.compile(r"url\((https://[^)]+\.woff2)\)")


def main() -> int:
    if not os.path.exists(SRC_CSS):
        print("source stylesheet not found:", SRC_CSS)
        return 1

    with open(SRC_CSS, "r", encoding="utf-8") as fh:
        css = fh.read()

    os.makedirs(OUT_FONT_DIR, exist_ok=True)

    out_blocks = []
    kept = 0
    skipped = 0
    downloaded = 0

    for m in BLOCK_RE.finditer(css):
        subset = (m.group(2) or "").lower()
        block = m.group(3)

        # Keep only latin. A heritage site in English + Hindi does not
        # need cyrillic or greek coverage.
        if subset and subset != "latin":
            skipped += 1
            continue
        if not subset:
            # No subset comment — keep it rather than silently drop a
            # face we cannot classify.
            pass

        um = URL_RE.search(block)
        if not um:
            out_blocks.append(block)
            continue

        url = um.group(1)
        # Deterministic local name: family + weight + style.
        fam = re.search(r"font-family:\s*'([^']+)'", block)
        wt = re.search(r"font-weight:\s*(\d+)", block)
        st = re.search(r"font-style:\s*(\w+)", block)
        slug = (
            (fam.group(1) if fam else "font")
            .lower()
            .replace(" ", "-")
        )
        name = f"{slug}-{wt.group(1) if wt else '400'}-{st.group(1) if st else 'normal'}.woff2"
        dest = os.path.join(OUT_FONT_DIR, name)

        if not os.path.exists(dest):
            r = subprocess.run(
                ["curl.exe", "-sS", "-L", "-A", UA, "-o", dest, url],
                capture_output=True,
                text=True,
            )
            if r.returncode != 0 or not os.path.exists(dest):
                print("FAILED:", name, r.stderr.strip()[:200])
                return 1
            downloaded += 1

        if not os.path.exists(dest) or os.path.getsize(dest) == 0:
            print("empty file:", name)
            return 1

        # Relative from /fonts/ to the css that will live beside it.
        local = f"url('./{name}') format('woff2')"
        new_block = URL_RE.sub(local, block, count=1)
        out_blocks.append(new_block)
        kept += 1

    if kept == 0:
        print("no latin blocks parsed — stylesheet format may have changed")
        return 1

    out_path = os.path.join(OUT_FONT_DIR, "fonts.css")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(
            "/* Generated by tools/fetch_fonts.py — do not edit by hand.\n"
            "   Latin subset only, self-hosted so the site needs no network. */\n\n"
        )
        fh.write("\n".join(out_blocks))
        fh.write("\n")

    total = sum(
        os.path.getsize(os.path.join(OUT_FONT_DIR, f))
        for f in os.listdir(OUT_FONT_DIR)
        if f.endswith(".woff2")
    )
    print(f"faces kept   : {kept}")
    print(f"blocks skipped (non-latin): {skipped}")
    print(f"newly downloa: {downloaded}")
    print(f"fonts.css    : {out_path}")
    print(f"total woff2  : {total/1024:.1f} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
